// Auto-generates docs/components-catalog.md from component inline schemas.
// Authors don't edit this — `bun run build` rewrites it from the component files.

import { mkdir, readFile, writeFile } from 'fs/promises'
import { join } from 'path'
import type { ComponentSchema } from './compose'

export async function writeComponentsReadme(
  root: string,
  templates: Map<string, string>,
  schemas: Map<string, ComponentSchema>,
) {
  const lines: string[] = []
  lines.push('# Component catalog')
  lines.push('')
  lines.push('Auto-generated by `build/docs.ts` from the inline schema comment at the top of each `src/components/*.html` file. Do not hand-edit. Run `bun run build` to regenerate.')
  lines.push('')
  lines.push('See `docs/components.md` for the authoring contract.')
  lines.push('')

  const names = [...templates.keys()].sort()
  lines.push('## Index')
  lines.push('')
  for (const name of names) {
    const schema = schemas.get(name)
    const desc = schema?.description ?? ''
    lines.push(`- [\`<${name} />\`](#${name.toLowerCase()})${desc ? ` — ${desc}` : ''}`)
  }
  lines.push('')

  for (const name of names) {
    const schema = schemas.get(name)
    lines.push(`## ${name}`)
    lines.push('')
    if (schema?.description) {
      lines.push(schema.description)
      lines.push('')
    }
    if (schema?.attrs && Object.keys(schema.attrs).length) {
      lines.push('### Attributes')
      lines.push('')
      lines.push('| Name | Required | Type / enum | Description |')
      lines.push('|---|---|---|---|')
      for (const [k, rule] of Object.entries(schema.attrs)) {
        const required = rule.required ? '✓' : ''
        const type = rule.enum ? `\`${rule.enum.join(' \\| ')}\`` : rule.type ?? 'string'
        const description = rule.description ?? ''
        lines.push(`| \`${k}\` | ${required} | ${type} | ${description} |`)
      }
      lines.push('')
    }
    if (schema?.schema) {
      lines.push(`Emits JSON-LD: \`${schema.schema.type}\`.`)
      lines.push('')
    }
    const example = exampleInvocation(name, schema)
    if (example) {
      lines.push('### Example')
      lines.push('')
      lines.push('```html')
      lines.push(example)
      lines.push('```')
      lines.push('')
    }
  }

  // Write only if content changed. The output lives under docs/ (not watched), so a stray write
  // wouldn't loop the dev build — but the no-op-skip is still cleaner.
  const next = lines.join('\n')
  const docsDir = join(root, 'docs')
  const path = join(docsDir, 'components-catalog.md')
  await mkdir(docsDir, { recursive: true })
  const prev = await readFile(path, 'utf8').catch(() => null)
  if (prev !== next) {
    await writeFile(path, next)
  }
}

function exampleInvocation(name: string, schema?: ComponentSchema): string {
  if (!schema?.attrs) return `<${name} />`
  const parts: string[] = []
  for (const [k, rule] of Object.entries(schema.attrs)) {
    if (!rule.required) continue
    if (rule.enum) parts.push(`${k}="${rule.enum[0]}"`)
    else if (rule.type === 'number') parts.push(`${k}="1"`)
    else parts.push(`${k}="..."`)
  }
  return parts.length ? `<${name} ${parts.join(' ')} />` : `<${name} />`
}
