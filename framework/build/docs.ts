// Auto-generates the project-local component catalog from inline schemas.

import { mkdir, readFile, writeFile } from 'fs/promises'
import { join } from 'path'
import type { ComponentSchema, SchemaAttr } from './compose'

export async function writeComponentsReadme(
  root: string,
  templates: Map<string, string>,
  schemas: Map<string, ComponentSchema>,
) {
  const lines: string[] = []
  lines.push('# Component catalog')
  lines.push('')
  lines.push('Auto-generated by `framework/build/docs.ts` from the inline schema comment at the top of each `src/components/*.html` file. Do not hand-edit. Run `bun run build` to regenerate.')
  lines.push('')
  lines.push('Purpose: give agents one deterministic source for project component contracts, slots, variants, schema metadata, and accessibility requirements before editing routes.')
  lines.push('')
  lines.push('See `framework/docs/framework/05-components.md` in the framework package for the authoring contract.')
  lines.push('')

  const names = [...templates.keys()].sort()
  lines.push('## Index')
  lines.push('')
  for (const name of names) {
    const schema = schemas.get(name)
    const desc = schema?.description ?? ''
    lines.push(`- [\`<${name} />\`](#${name.toLowerCase()})${desc ? ` — ${desc}` : ''}`)
  }
  lines.push('')

  for (const name of names) {
    const schema = schemas.get(name)
    const template = templates.get(name) ?? ''
    const slots = slotNames(template, schema)
    const variantAttrs = Object.entries(schema?.attrs ?? {}).filter(([, rule]) => rule.enum?.length)
    const classAttrs = Object.entries(schema?.attrs ?? {}).filter(([, rule]) => rule.asClass)
    const notes = accessibilityNotes(schema)

    lines.push(`## ${name}`)
    lines.push('')
    if (schema?.description) {
      lines.push(schema.description)
      lines.push('')
    }

    lines.push('### Contract')
    lines.push('')
    lines.push(`- Tag: \`<${name}>\`${slots.includes('default') ? ' wraps default slot content' : ' can be self-closing'}.`)
    lines.push(`- Slots: ${slots.length ? slots.map((slot) => slot === 'default' ? '`default`' : `\`${slot}\``).join(', ') : 'none detected'}.`)
    lines.push(`- Unknown attributes: ${schema?.allowUnknownAttrs ? 'allowed' : 'rejected when schema exists'}.`)
    if (classAttrs.length) {
      lines.push(`- Class-mapped attrs: ${classAttrs.map(([attr]) => `\`${attr}\``).join(', ')} append value to root class.`)
    }
    lines.push('')

    if (schema?.attrs && Object.keys(schema.attrs).length) {
      lines.push('### Attributes')
      lines.push('')
      lines.push('| Name | Required | Type / enum | Description |')
      lines.push('|---|---|---|---|')
      for (const [k, rule] of Object.entries(schema.attrs)) {
        const required = rule.required ? 'yes' : 'no'
        const type = attrType(rule)
        const description = rule.description ?? ''
        lines.push(`| \`${k}\` | ${required} | ${type} | ${description} |`)
      }
      lines.push('')
    }

    if (variantAttrs.length) {
      lines.push('### Variants / enums')
      lines.push('')
      for (const [attr, rule] of variantAttrs) {
        lines.push(`- \`${attr}\`: ${rule.enum!.map((value) => `\`${value}\``).join(', ')}`)
      }
      lines.push('')
    }

    if (schema?.schema) {
      lines.push('### Schema metadata')
      lines.push('')
      lines.push(`- Emits JSON-LD: \`${schema.schema.type}\`.`)
      if (schema.schema.map && Object.keys(schema.schema.map).length) {
        lines.push(`- Field map: ${Object.entries(schema.schema.map).map(([out, attr]) => `\`${out}\` ← \`${attr}\``).join(', ')}.`)
      }
      lines.push('')
    }

    if (notes.length) {
      lines.push('### Accessibility notes')
      lines.push('')
      for (const note of notes) lines.push(`- ${note}`)
      lines.push('')
    }

    const example = exampleInvocation(name, schema, slots)
    lines.push('### Example')
    lines.push('')
    lines.push('```html')
    lines.push(example)
    lines.push('```')
    lines.push('')
  }

  // Generated catalogs are project state. The framework package does not ship a site-specific catalog.
  const next = lines.join('\n')
  const docsDir = join(root, '.snz')
  const path = join(docsDir, 'components-catalog.md')
  await mkdir(docsDir, { recursive: true })
  const prev = await readFile(path, 'utf8').catch(() => null)
  if (prev !== next) {
    await writeFile(path, next)
  }
}

function attrType(rule: SchemaAttr): string {
  if (rule.enum) return `\`${rule.enum.join(' \\| ')}\``
  return rule.type ?? 'string'
}

function slotNames(template: string, schema?: ComponentSchema): string[] {
  const names = new Set(schema?.slots ?? [])
  if (/\{\{slot\}\}/.test(template)) names.add('default')
  for (const match of template.matchAll(/\{\{slot:([\w-]+)\}\}/g)) names.add(match[1])
  return [...names].sort((a, b) => a === 'default' ? -1 : b === 'default' ? 1 : a.localeCompare(b))
}

function accessibilityNotes(schema?: ComponentSchema): string[] {
  return schema?.attrs?.alt?.required
    ? ['`alt` is required; use `alt=""` only for decorative images.']
    : []
}

function exampleInvocation(name: string, schema: ComponentSchema | undefined, slots: string[]): string {
  const attrs = exampleAttrs(schema)
  const attrText = Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(' ')
  const open = attrText ? `<${name} ${attrText}>` : `<${name}>`
  if (slots.includes('default')) return `${open}${exampleSlot()}</${name}>`
  return attrText ? `<${name} ${attrText} />` : `<${name} />`
}

function exampleAttrs(schema?: ComponentSchema): Record<string, string> {
  const attrs: Record<string, string> = {}
  for (const [key, rule] of Object.entries(schema?.attrs ?? {})) {
    if (rule.required) attrs[key] = exampleValue(key, rule)
  }
  return attrs
}

function exampleValue(key: string, rule: SchemaAttr): string {
  if (rule.enum) return rule.enum[0]
  if (rule.type === 'number') return '1'
  if (rule.type === 'boolean') return 'true'
  if (key === 'href') return '/'
  if (key === 'src') return 'example'
  if (key === 'alt') return 'Descriptive alt text'
  if (key === 'title') return 'Example title'
  return 'Example'
}

function exampleSlot(): string {
  return 'Content'
}
