// Auto-generates a component catalog from component inline schemas.
// Framework repo writes framework/docs/components-catalog.md; client projects write .snz/components-catalog.md.

import { mkdir, readFile, stat, writeFile } from 'fs/promises'
import { join } from 'path'
import type { ComponentSchema, SchemaAttr } from './compose'

export async function writeComponentsReadme(
  root: string,
  templates: Map<string, string>,
  schemas: Map<string, ComponentSchema>,
) {
  const lines: string[] = []
  lines.push('# Component catalog')
  lines.push('')
  lines.push('Auto-generated by `framework/build/docs.ts` from the inline schema comment at the top of each `src/components/*.html` file. Do not hand-edit. Run `bun run build` to regenerate.')
  lines.push('')
  lines.push('Purpose: give agents one deterministic source for built-in component contracts, slots, variants, schema metadata, accessibility notes, and valid usage examples before editing routes or inventing patterns.')
  lines.push('')
  lines.push('See `framework/docs/components.md` in the framework package for the authoring contract.')
  lines.push('')

  const names = [...templates.keys()].sort()
  lines.push('## Index')
  lines.push('')
  for (const name of names) {
    const schema = schemas.get(name)
    const desc = schema?.description ?? ''
    lines.push(`- [\`<${name} />\`](#${name.toLowerCase()})${desc ? ` — ${desc}` : ''}`)
  }
  lines.push('')

  for (const name of names) {
    const schema = schemas.get(name)
    const template = templates.get(name) ?? ''
    const slots = slotNames(template, schema)
    const variantAttrs = Object.entries(schema?.attrs ?? {}).filter(([, rule]) => rule.enum?.length)
    const classAttrs = Object.entries(schema?.attrs ?? {}).filter(([, rule]) => rule.asClass)
    const notes = accessibilityNotes(name, schema)

    lines.push(`## ${name}`)
    lines.push('')
    if (schema?.description) {
      lines.push(schema.description)
      lines.push('')
    }

    lines.push('### Contract')
    lines.push('')
    lines.push(`- Tag: \`<${name}>\`${slots.includes('default') ? ' wraps default slot content' : ' can be self-closing'}.`)
    lines.push(`- Slots: ${slots.length ? slots.map((slot) => slot === 'default' ? '`default`' : `\`${slot}\``).join(', ') : 'none detected'}.`)
    lines.push(`- Unknown attributes: ${schema?.allowUnknownAttrs ? 'allowed' : 'rejected when schema exists'}.`)
    if (classAttrs.length) {
      lines.push(`- Class-mapped attrs: ${classAttrs.map(([attr]) => `\`${attr}\``).join(', ')} append value to root class.`)
    }
    lines.push('')

    if (schema?.attrs && Object.keys(schema.attrs).length) {
      lines.push('### Attributes')
      lines.push('')
      lines.push('| Name | Required | Type / enum | Description |')
      lines.push('|---|---|---|---|')
      for (const [k, rule] of Object.entries(schema.attrs)) {
        const required = rule.required ? 'yes' : 'no'
        const type = attrType(rule)
        const description = rule.description ?? ''
        lines.push(`| \`${k}\` | ${required} | ${type} | ${description} |`)
      }
      lines.push('')
    }

    if (variantAttrs.length) {
      lines.push('### Variants / enums')
      lines.push('')
      for (const [attr, rule] of variantAttrs) {
        lines.push(`- \`${attr}\`: ${rule.enum!.map((value) => `\`${value}\``).join(', ')}`)
      }
      lines.push('')
    }

    if (schema?.schema) {
      lines.push('### Schema metadata')
      lines.push('')
      lines.push(`- Emits JSON-LD: \`${schema.schema.type}\`.`)
      if (schema.schema.map && Object.keys(schema.schema.map).length) {
        lines.push(`- Field map: ${Object.entries(schema.schema.map).map(([out, attr]) => `\`${out}\` ← \`${attr}\``).join(', ')}.`)
      }
      lines.push('')
    }

    if (notes.length) {
      lines.push('### Accessibility notes')
      lines.push('')
      for (const note of notes) lines.push(`- ${note}`)
      lines.push('')
    }

    const example = exampleInvocation(name, schema, slots)
    lines.push('### Example')
    lines.push('')
    lines.push('```html')
    lines.push(example)
    lines.push('```')
    lines.push('')
  }

  // Write only if content changed. Framework repo keeps the committed catalog in framework/docs;
  // client projects keep generated agent context in ignored .snz state.
  const next = lines.join('\n')
  const frameworkDocsDir = join(root, 'framework', 'docs')
  const hasFrameworkDocs = await stat(frameworkDocsDir).then((entry) => entry.isDirectory()).catch(() => false)
  const docsDir = hasFrameworkDocs ? frameworkDocsDir : join(root, '.snz')
  const path = join(docsDir, 'components-catalog.md')
  await mkdir(docsDir, { recursive: true })
  const prev = await readFile(path, 'utf8').catch(() => null)
  if (prev !== next) {
    await writeFile(path, next)
  }
}

function attrType(rule: SchemaAttr): string {
  if (rule.enum) return `\`${rule.enum.join(' \\| ')}\``
  return rule.type ?? 'string'
}

function slotNames(template: string, schema?: ComponentSchema): string[] {
  const names = new Set(schema?.slots ?? [])
  if (/\{\{slot\}\}/.test(template)) names.add('default')
  for (const match of template.matchAll(/\{\{slot:([\w-]+)\}\}/g)) names.add(match[1])
  return [...names].sort((a, b) => a === 'default' ? -1 : b === 'default' ? 1 : a.localeCompare(b))
}

function accessibilityNotes(name: string, schema?: ComponentSchema): string[] {
  const notes: string[] = []
  if (schema?.attrs?.alt?.required) notes.push('`alt` is required; use `alt=""` only for decorative images.')
  if (schema?.attrs?.title?.required && name === 'Embed') notes.push('`title` is required for iframe accessibility.')
  if (name === 'Accordion') notes.push('Use clear `summary` text; `group` makes matching disclosures mutually exclusive.')
  if (name === 'Button' || name === 'Link') notes.push('Use meaningful visible `label`; keep destination in `href`.')
  if (name === 'Logo') notes.push('If slot contains image or SVG mark, keep image `alt=""` when adjacent text names site.')
  if (name === 'Section') notes.push('When linking to section, provide stable `id`; section content should include heading when it starts new topic.')
  if (name === 'SEO') notes.push('Place in route `<head>` wrapper; include page-specific `title` and `description` when defaults are not enough.')
  return notes
}

function exampleInvocation(name: string, schema: ComponentSchema | undefined, slots: string[]): string {
  const attrs = exampleAttrs(name, schema)
  const attrText = Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(' ')
  const open = attrText ? `<${name} ${attrText}>` : `<${name}>`
  if (slots.includes('default')) return `${open}${exampleSlot(name)}</${name}>`
  return attrText ? `<${name} ${attrText} />` : `<${name} />`
}

function exampleAttrs(name: string, schema?: ComponentSchema): Record<string, string> {
  const custom = namedExampleAttrs(name)
  const attrs: Record<string, string> = {}
  for (const [key, rule] of Object.entries(schema?.attrs ?? {})) {
    if (custom[key]) attrs[key] = custom[key]
    else if (rule.required) attrs[key] = exampleValue(key, rule)
  }
  return attrs
}

function namedExampleAttrs(name: string): Record<string, string> {
  const examples: Record<string, Record<string, string>> = {
    Accordion: { summary: 'Question?', body: 'Answer copy.' },
    Button: { href: '/contact/', label: 'Contact' },
    Embed: { src: 'https://www.youtube.com/embed/dQw4w9WgXcQ', title: 'Product demo' },
    Footer: { siteName: 'Example Studio' },
    Grid: { cols: '3-2' },
    Image: { src: 'hero', alt: 'Product interface', max: '1200' },
    Link: { href: '/about/', label: 'About' },
    Logo: { siteName: 'Example Studio' },
    SEO: { title: 'About', description: 'Short page description.' },
    Section: { id: 'intro' },
  }
  return examples[name] ?? {}
}

function exampleValue(key: string, rule: SchemaAttr): string {
  if (rule.enum) return rule.enum[0]
  if (rule.type === 'number') return '1'
  if (rule.type === 'boolean') return 'true'
  if (key === 'href') return '/'
  if (key === 'src') return 'example'
  if (key === 'alt') return 'Descriptive alt text'
  if (key === 'title') return 'Example title'
  return 'Example'
}

function exampleSlot(name: string): string {
  if (name === 'Code') return 'const ok = true'
  if (name === 'Markdown') return '\n## Heading\n\nMarkdown body.\n'
  if (name === 'Logo') return ''
  if (name === 'Grid') return '\n  <Card><h2>One</h2><p>Copy.</p></Card>\n  <Card><h2>Two</h2><p>Copy.</p></Card>\n'
  if (name === 'Section') return '\n  <h1>Intro</h1>\n  <p>Page copy.</p>\n'
  if (name === 'Card') return '<h2>Feature</h2><p>Short copy.</p>'
  if (name === 'Stack') return '<h2>Heading</h2><p>Copy.</p>'
  return 'Content'
}
